public class DemoArray3 {
    public static void main(String[] args) {
        double[] salaries = {16.25, 17.55, 18.25, 19,85};
        System.out.println("Salaries one by one are: ");
        for (int i = 0; i < salaries.length; i++) {
            System.out.println(salaries[i]);
        }
    }
}
